/* Requirements
1. Create a class named NumberAnalyzer.
2. Declare the main method.
3. Use a for loop to count from 1 through 10.
4. Inside the loop, use System.out.println() to print each number.
5. Use an if statement to check whether the number is even.
6. If the number is even, print "Even number!".
*/
class NumberAnalyzer {
    public static void main(String[] args) {

     for (int i = 1; i <= 10; i++) {
         System.out.println(i);

         if (i % 2 == 0) {
             System.out.println("Even number!");
         }
         
     }
            
        
        

        
  }  
}
